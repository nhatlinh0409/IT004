CREATE DATABASE QUANLYHOATDONGBANTHUOC
USE QUANLYHOATDONGBANTHUOC
SET DATEFORMAT DMY
CREATE TABLE KHACHHANG (
	MAKH CHAR(5) PRIMARY KEY,
	TENKH NVARCHAR(50),
	DIACHI NVARCHAR(50),
	LOAIKH NVARCHAR(20)
)
CREATE TABLE THUOC (
	MATHUOC CHAR(5) PRIMARY KEY,
	TENTHUOC NVARCHAR(50),
	NGUONGOC NVARCHAR(20),
	GIA MONEY
)
CREATE TABLE DONTHUOC (
	MADT CHAR(5) PRIMARY KEY,
	NGDT SMALLDATETIME,
	MAKH CHAR(5) FOREIGN KEY REFERENCES KHACHHANG(MAKH),
)
CREATE TABLE CTDT (
	MADT CHAR(5) FOREIGN KEY REFERENCES DONTHUOC(MADT),
	MATHUOC CHAR(5) FOREIGN KEY REFERENCES THUOC(MATHUOC),
	SOLUONG INT
	PRIMARY KEY (MADT, MATHUOC)
)
