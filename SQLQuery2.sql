---7---
SELECT KH.MAKH, TENKH, SUM(SOLUONG*GIA) 'Tong_gia_tri'
FROM KHACHHANG KH, THUOC T, DONTHUOC DT, CTDT CT
WHERE KH.MAKH = DT.MAKH
	AND T.MATHUOC = CT.MATHUOC
	AND DT.MADT = CT.MADT
	AND YEAR(NGDT) = 2018
GROUP BY KH.MAKH, TENKH
ORDER BY SUM(SOLUONG*GIA) DESC;
---8---
SELECT LOAIKH, SUM(SOLUONG*GIA) 'Tong_gia_tri'
FROM KHACHHANG KH, THUOC T, DONTHUOC DT, CTDT CT
WHERE KH.MAKH = DT.MAKH
	AND T.MATHUOC = CT.MATHUOC
	AND DT.MADT = CT.MADT
	AND LOAIKH = 'VIP'
GROUP BY KH.MAKH, LOAIKH;