CREATE TRIGGER TG_NGHD_HD
ON HOADON
AFTER INSERT
AS
BEGIN
	IF EXISTS (
		SELECT *
		FROM INSERTED I, NHANVIEN NV
		WHERE I.MANV = NV.MANV
			AND NGHD < NGVL
	)
	BEGIN
		RAISERROR ('Ngay ban hang phai >= ngay vao lam', 16, 1);
		ROLLBACK;
	END
	ELSE 
	BEGIN
		PRINT 'Them mot hoa don thanh cong'
	END
END;
GO
