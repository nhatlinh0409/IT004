CREATE TRIGGER TG_NGHD_KH
ON KHACHHANG
AFTER INSERT
AS
BEGIN
	IF EXISTS (
		SELECT *
		FROM INSERTED I, HOADON HD
		WHERE I.MAKH = HD.MAKH
			AND NGHD < NGDK
	)
	BEGIN
		RAISERROR ('Ngay mua hang phai >= ngay dang ky thanh vien', 16, 1);
		ROLLBACK;
	END
	ELSE
	BEGIN
		PRINT 'Them mot hoa don thanh cong'
	END
END;
GO
