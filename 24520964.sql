UPDATE HOCVIEN
SET DIEMTB = TinhToan.DTBHV
FROM HOCVIEN HV
JOIN (
	SELECT DiemCuoi.MAHV, AVG(DiemCuoi.DIEM) AS DTBHV
	FROM (
		SELECT KQT.MAHV, KQT.MAMH, KQT.DIEM
		FROM KETQUATHI KQT
		JOIN (
			SELECT MAHV, MAMH, MAX(LANTHI) AS MaxLan
			FROM KETQUATHI
			GROUP BY MAHV, MAMH)
		AS MaxLanThi ON KQT.MAHV = MaxLanThi.MAHV
					AND KQT.MAMH = MaxLanThi.MAMH
					AND KQT.LANTHI = MaxLanThi.MaxLan)
	AS DiemCuoi
	GROUP BY DiemCuoi.MAHV)
AS TinhToan ON HV.MAHV = TinhToan.MAHV;

