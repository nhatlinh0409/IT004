CREATE TRIGGER TG_INS_UP_DE_CT ON CTHD
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
	UPDATE HOADON
	SET TRIGIA = (
		SELECT SUM(SL*GIA)
		FROM CTHD CT, SANPHAM SP
		WHERE CT.MASP = SP.MASP
			AND CT.SOHD = HOADON.SOHD
	)
	WHERE SOHD IN (SELECT SOHD FROM INSERTED)
		OR SOHD IN (SELECT SOHD FROM DELETED)
END;
GO
---14---
CREATE TRIGGER TG_INS_UP_DE_HD ON HOADON
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
	UPDATE KHACHHANG
	SET DOANHSO = (
		SELECT SUM(TRIGIA)
		FROM HOADON HD
		WHERE HD.MAKH = KHACHHANG.MAKH
	)
	WHERE MAKH IN (SELECT MAKH FROM INSERTED)
		OR MAKH IN (SELECT MAKH FROM DELETED)
END

