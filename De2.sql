CREATE DATABASE QUANLYLAIXE
USE QUANLYLAIXE
SET DATEFORMAT DMY
CREATE TABLE NHANVIEN (
	MANV CHAR(5) PRIMARY KEY,
	HOTEN VARCHAR(20),
	NGAYVL SMALLDATETIME,
	HSLUONG NUMERIC(4,2),
	MAPHONG CHAR(5) FOREIGN KEY REFERENCES PHONGBAN(MAPHONG)
)
CREATE TABLE PHONGBAN (
	MAPHONG CHAR(5) PRIMARY KEY,
	TENPHONG VARCHAR(25),
	TRUONGPHONG CHAR(5) FOREIGN KEY REFERENCES NHANVIEN(MANV)
)
CREATE TABLE XE (
	MAXE CHAR(5),
	LOAIXE VARCHAR(20),
	SOCHONGOI INT,
	NAMSX INT
)
CREATE TABLE PHANCONG (
	MAPC CHAR(5),
	MANV CHAR(5),
	MAXE CHAR(5),
	NGAYDI SMALLDATETIME,
	NGAYVE SMALLDATETIME,
	NOIDEN VARCHAR(25)
)
---2.1---
ALTER TABLE XE
ADD CONSTRAINT CK_XE
CHECK (NAMSX >= 2006);
---2.2---
GO
CREATE TRIGGER TG_NV
ON NHANVIEN
AFTER INSERT
AS BEGIN
	IF EXISTS (
		SELECT I.MANV
		FROM INSERTED I, PHONGBAN PB, PHANCONG PC, XE
		WHERE TENPHONG = N'Ngoại thành'
			AND LOAIXE <> 'Toyota')
	BEGIN
		RAISERROR (N'Lỗi', 16, 1);
		ROLLBACK;
	END
END;
---3.1---
SELECT NV.MANV, HOTEN
FROM NHANVIEN NV, PHONGBAN PB, PHANCONG PC, XE
WHERE NV.MAPHONG = PB.MAPHONG
	AND NV.MANV = PC.MANV
	AND PC.MAXE = XE.MAXE
	AND TENPHONG = N'Nội thành'
	AND LOAIXE = 'Toyota'
	AND SOCHONGOI = 4;
---3.2---
SELECT NV.MANV, HOTEN
FROM NHANVIEN NV, PHONGBAN PB, PHANCONG PC, XE
WHERE NV.MAPHONG = PB.MAPHONG
	AND NV.MANV = PC.MANV
	AND PC.MAXE = XE.MAXE
	AND NV.MANV IN (
		SELECT TRUONGPHONG
		FROM PHONGBAN)
GROUP BY NV.MANV, HOTEN
HAVING COUNT(DISTINCT XE.MAXE) = 
		(SELECT COUNT(MAXE)
		FROM XE);
---3.3---
SELECT NV.MAPHONG, NV.MANV, HOTEN
FROM NHANVIEN NV, PHANCONG PC, XE
WHERE NV.MANV = PC.MANV
	AND PC.MAXE = XE.MAXE
	AND LOAIXE = 'Toyota'
GROUP BY NV.MAPHONG, NV.MANV, HOTEN
HAVING COUNT(DISTINCT PC.MAXE) <= ALL (
	SELECT COUNT(DISTINCT X.MAXE)
	FROM PHANCONG P, NHANVIEN V, XE X
	WHERE P.MANV = V.MANV
		AND X.MAXE = P.MAXE
		AND LOAIXE = 'Toyota'
		AND NV.MAPHONG = V.MAPHONG
	GROUP BY V.MANV);