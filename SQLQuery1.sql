CREATE TRIGGER TG_TGNUOI
ON DOTCN
AFTER INSERT
AS BEGIN
	IF EXISTS (
		SELECT *
		FROM INSERTED I, GIONGVN G
		WHERE I.MAGIONG = G.MAGIONG
			AND G.LOAIVN = 'Bo'
			AND DATEDIFF(MONTH, I.NGBD, I.NGXUATDK) < 12
	)
	BEGIN
		RAISERROR ('Loi', 16, 1);
		ROLLBACK;
	END
END;
