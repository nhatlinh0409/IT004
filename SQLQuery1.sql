CREATE TRIGGER TG_DOTCN
ON DOTCN
AFTER INSERT
AS BEGIN
	IF EXISTS (
		SELECT MADOTCN
		FROM DOTCN
		WHERE SLVN > 100
			AND PHGTHUC = 'Tha tu do'
	)
	BEGIN
		RAISERROR ('Loi', 16, 1);
		ROLLBACK;
	END
END;
