SELECT LOAIVN, G.MAGIONG
FROM GIONGVN G, GPCN, CTGP
WHERE G.MAGIONG = CTGP.MAGIONG
	AND CTGP.MAGP = GPCN.MAGP
	AND YEAR(NGCAP) = 2024
GROUP BY LOAIVN, G.MAGIONG
HAVING SUM(SL) >= ALL (
	SELECT SUM(SL)
	FROM GPCN G1, CTGP C, GIONGVN GVN
	WHERE C.MAGIONG = GVN.MAGIONG
		AND C.MAGP = G1.MAGP
		AND G.LOAIVN = GVN.LOAIVN
		AND YEAR(NGCAP) = 2024
	GROUP BY GVN.MAGIONG);
