SELECT LOAIVN, PHGTHUC, AVG(DATEDIFF(MONTH, D.NGBD, D.NGXUATDK))
FROM DOTCN D, GIONGVN G
WHERE D.MAGIONG = G.MAGIONG
GROUP BY LOAIVN, PHGTHUC;
