SELECT G.MAGIONG, TENGIONG
FROM GIONGVN G, DOTCN D
WHERE G.MAGIONG = D.MAGIONG
	AND LOAIVN = 'Bo'
	AND PHGTHUC = 'Tha tu do'
	AND MONTH(NGXUATDK) = 12
	AND YEAR(NGXUATDK) = 2024;
---6---
SELECT CS.MACS, TENCS
FROM CSCHANNUOI CS, DOTCN D, GIONGVN G
WHERE CS.MACS = D.MACS
	AND D.MAGIONG = G.MAGIONG
	AND G.LOAIVN = 'De'
	AND YEAR(NGBD) = 2024
	AND CS.MACS NOT IN (
		SELECT GP.MACS
		FROM GPCN GP, CTGP CT, GIONGVN G2
		WHERE GP.MAGP = CT.MAGP
			AND CT.MAGIONG = G2.MAGIONG
			AND G2.LOAIVN = 'De');

