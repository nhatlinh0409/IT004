SELECT CS.MACS, TENCS
FROM CSCHANNUOI CS, GPCN G, CTGP C, GIONGVN GVN
WHERE CS.MACS = G.MACS
	AND G.MAGP = C.MAGP
	AND C.MAGIONG = GVN.MAGIONG
	AND LOAIVN = 'Bo'
	AND SL >= 20
GROUP BY CS.MACS, TENCS
HAVING COUNT(DISTINCT GVN.MAGIONG) = (
	SELECT COUNT(DISTINCT G.MAGIONG)
	FROM GIONGVN G
	WHERE LOAIVN = 'Bo');