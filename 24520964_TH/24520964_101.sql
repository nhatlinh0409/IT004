CREATE DATABASE QUANLYCHOTHUEPHONGTRO
USE QUANLYCHOTHUEPHONGTRO
SET DATEFORMAT DMY
CREATE TABLE PHONGTRO (
	MAPT CHAR(5) PRIMARY KEY,
	TENPT NVARCHAR(50),
	DIENTICH FLOAT,
	GIAPT MONEY,
	TINHTRANGPT NVARCHAR(20)
)
CREATE TABLE CUDAN (
	MACD CHAR(5) PRIMARY KEY,
	HOTEN NVARCHAR(50),
	CCCD NVARCHAR(12),
	DIACHI NVARCHAR(100),
	SODT VARCHAR(15),
	NGAYTHUE SMALLDATETIME,
	TRANGTHAICD NVARCHAR(15)
)
CREATE TABLE HOPDONG (
	MAHD CHAR(5) PRIMARY KEY,
	MACD CHAR(5) FOREIGN KEY REFERENCES CUDAN(MACD),
	MAPT CHAR(5) FOREIGN KEY REFERENCES PHONGTRO(MAPT),
	NGAYKY SMALLDATETIME,
	NGAYHETHAN SMALLDATETIME,
	TRANGTHAIHD NVARCHAR(20)
)
CREATE TABLE DICHVU (
	MADV CHAR(5) PRIMARY KEY,
	TENDV NVARCHAR(50),
	DONGIA MONEY
)
CREATE TABLE PHIEUTINHTIEN (
	MAPTT CHAR(5) PRIMARY KEY,
	MAHD CHAR(5) FOREIGN KEY REFERENCES HOPDONG(MAHD),
	SOTIENDICHVU MONEY,
	SOTIENTHUEPT MONEY,
	TONGTIENTT MONEY,
	NGAYTINHTIEN SMALLDATETIME,
	TINHTRANGTT NVARCHAR(20),
	PHUONGTHUCTT NVARCHAR(20)
)
CREATE TABLE CHITIETTTDV (
	MAPTT CHAR(5) FOREIGN KEY REFERENCES PHIEUTINHTIEN(MAPTT),
	MADV CHAR(5) FOREIGN KEY REFERENCES DICHVU(MADV),
	CHISODV FLOAT,
	THANHTIEN MONEY,
	CONSTRAINT PK_CT PRIMARY KEY (MAPTT, MADV)
)

---2.1---
ALTER TABLE PHONGTRO
ADD CONSTRAINT CK_PT
CHECK (DIENTICH BETWEEN 10 AND 50);
---2.2---
ALTER TABLE PHIEUTINHTIEN
ADD CONSTRAINT CK_PTT
CHECK (TINHTRANGTT IN (N'Chưa thanh toán', N'Đã thanh toán'));
---2.3---
GO
CREATE TRIGGER TG_CTSDDV
ON CHITIETTTDV
AFTER INSERT
AS BEGIN
	UPDATE CHITIETTTDV
	SET THANHTIEN = CHISODV * (
			SELECT DONGIA
			FROM DICHVU
			WHERE MADV = CHITIETTTDV.MADV)
	WHERE MADV IN (SELECT MADV FROM INSERTED)
		AND MAPTT IN (SELECT MAPTT FROM INSERTED);
END;
---3.1---
SELECT PT.MAPT, TENPT, CD.MACD, HOTEN
FROM PHONGTRO PT, CUDAN CD, HOPDONG HD
WHERE PT.MAPT = HD.MAPT
	AND CD.MACD = HD.MACD
	AND YEAR(NGAYKY) = 2024
	AND GIAPT > 5000000;
---3.2---
SELECT DV.MADV, TENDV 
FROM DICHVU DV, CHITIETTTDV CT, PHIEUTINHTIEN PTT
WHERE DV.MADV = CT.MADV
	AND CT.MAPTT = PTT.MAPTT
	AND MAHD = 'HD002'
	AND TINHTRANGTT = N'Đã thanh toán'
	AND YEAR(NGAYTINHTIEN) = 2024
	AND MONTH(NGAYTINHTIEN) = 11
INTERSECT
SELECT DV.MADV, TENDV 
FROM DICHVU DV, CHITIETTTDV CT, PHIEUTINHTIEN PTT
WHERE DV.MADV = CT.MADV
	AND CT.MAPTT = PTT.MAPTT
	AND MAHD = 'HD002'
	AND TINHTRANGTT = N'Đã thanh toán'
	AND YEAR(NGAYTINHTIEN) = 2024
	AND MONTH(NGAYTINHTIEN) = 12;
---3.3---
SELECT PTT.MAPTT, MAHD
FROM PHIEUTINHTIEN PTT, CHITIETTTDV CT, DICHVU DV
WHERE PTT.MAPTT = CT.MAPTT
	AND CT.MADV = DV.MADV
	AND YEAR(NGAYTINHTIEN) = 2024
	AND DONGIA <= 150000
GROUP BY PTT.MAPTT, MAHD
HAVING COUNT(DISTINCT DV.MADV) =
			(SELECT	COUNT(MADV)
			FROM DICHVU
			WHERE DONGIA <= 150000);
---3.4---
SELECT HD.MAHD, MACD, COUNT(MAPTT)
FROM HOPDONG HD, PHIEUTINHTIEN PTT
WHERE HD.MAHD = PTT.MAHD
	AND TINHTRANGTT = N'Đã thanh toán'
	AND PHUONGTHUCTT = N'Chuyển khoản'
	AND YEAR(NGAYTINHTIEN) = 2024
GROUP BY HD.MAHD, MACD;
---3.5---
SELECT CD.MACD, HOTEN
FROM CUDAN CD, HOPDONG HD, PHIEUTINHTIEN PTT
WHERE CD.MACD = HD.MACD
	AND HD.MAHD = PTT.MAHD
	AND YEAR(NGAYTINHTIEN) = 2024
	AND TINHTRANGTT = N'Đã thanh toán'
	AND CD.MACD IN (
			SELECT TOP 1 WITH TIES MACD
			FROM HOPDONG
			GROUP BY MACD
			ORDER BY COUNT(DISTINCT MAHD) DESC)
	GROUP BY CD.MACD, HOTEN
	HAVING SUM(TONGTIENTT) > 15000000

