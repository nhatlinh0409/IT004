CREATE DATABASE QUANLYTHUVIEN
USE QUANLYTHUVIEN
SET DATEFORMAT DMY
GO
CREATE TABLE SACH (
	MASACH CHAR(5) PRIMARY KEY,
	TENSACH NVARCHAR(1000),
	THELOAI NVARCHAR(30),
	DONGIA MONEY,
	SOLUONG INT
)
CREATE TABLE TACGIA (
	MATG CHAR(5) PRIMARY KEY,
	HOTEN NVARCHAR(50),
	QUOCTICH NVARCHAR(30),
	NGAYSINH SMALLDATETIME,
	DIENTHOAI VARCHAR(15)
)
CREATE TABLE TACGIA_SACH (
	MATG CHAR(5),
	MASACH CHAR(5),
	CONSTRAINT PR_TGS PRIMARY KEY (MATG, MASACH)
)
CREATE TABLE DOCGIA (
	MADG CHAR(5) PRIMARY KEY,
	TENDG NVARCHAR(50),
	DIACHI NVARCHAR(50),
	NGAYSINH SMALLDATETIME,
	DIENTHOAI VARCHAR(15),
	NGDK SMALLDATETIME
)
CREATE TABLE PHATHANH (
	MAPH CHAR(5),
	MASACH CHAR(5),
	NGAYPH SMALLDATETIME,
	SOLUONG INT,
	NXB NVARCHAR(100),
	LANPHATHANH INT
)
CREATE TABLE MUONSACH (
	MAMUON CHAR(5),
	MADG CHAR(5), 
	MASACH CHAR(5),
	NGAYMUON SMALLDATETIME,
	NGAYTRA SMALLDATETIME,
	TRANGTHAI NVARCHAR(20)
)

