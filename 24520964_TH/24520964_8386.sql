CREATE TRIGGER TG_PH
ON PHATHANH
AFTER INSERT, UPDATE
AS
BEGIN
	IF EXISTS (
		SELECT *
		FROM INSERTED I, TACGIA_SACH TGS, TACGIA TG
		WHERE I.MASACH = TGS.MASACH 
		AND TGS.MATG = TG.MATG
		AND NGAYPH <= NGAYSINH)
	BEGIN 
		RAISERROR (N'Lỗi ngày sinh lớn hơn ngày phát hành!', 16, 1);
		ROLLBACK;
	END
END;

