---5---
SELECT TG.MATG, HOTEN
FROM TACGIA TG, TACGIA_SACH TGS, SACH S, PHATHANH PH
WHERE TG.MATG = TGS.MATG
	AND TGS.MASACH =S.MASACH
	AND PH.MASACH = TGS.MASACH 
	AND THELOAI = N'Giáo trình'
	AND TENSACH = N'Cấu trúc rời rạc'
	AND NXB = N'ĐHQG-HCM';
---6---
SELECT TG.MATG, HOTEN, COUNT(PH.MASACH) 'So luong'
FROM TACGIA TG, PHATHANH PH, TACGIA_SACH TGS
WHERE TG.MATG = TGS.MATG
	AND TGS.MASACH = PH.MASACH
	AND YEAR(NGAYPH) = 2024
GROUP BY TG.MATG, HOTEN
ORDER  BY COUNT(PH.MASACH) DESC;
---7---
SELECT DG.MADG
FROM DOCGIA DG, MUONSACH MS, SACH S
WHERE DG.MADG = MS.MADG
	AND MS.MASACH = S.MASACH
	AND YEAR(NGAYMUON) = 2024
GROUP BY DG.MADG
HAVING COUNT(DISTINCT THELOAI) = 3;
---8---
SELECT NXB
FROM PHATHANH PH
LEFT JOIN MUONSACH MS ON PH.MASACH = MS.MASACH
GROUP BY NXB
HAVING COUNT(DISTINCT PH.MASACH) > 5
	AND COUNT(MAMUON) = 0;
---9---
SELECT DG.MADG, TENDG
FROM DOCGIA DG, MUONSACH MS, SACH S
WHERE DG.MADG = MS.MADG
	AND MS.MASACH = S.MASACH
	AND (THELOAI = N'Khoa học viễn tưởng'
	OR THELOAI = 'Kinh tế')
	AND YEAR(NGAYMUON) = 2024
GROUP BY DG.MADG, TENDG
HAVING COUNT(DISTINCT S.MASACH) 
		= (SELECT COUNT(MASACH)
		FROM SACH
		WHERE THELOAI IN (N'Khoa học viễn tưởng', N'Kinh tế'));
			
