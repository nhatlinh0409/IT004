---3.2---
SELECT BN.MABN, HOTENBN
FROM BENHNHAN BN, KHAMBENH KB, BACSI BS
WHERE BN.MABN = KB.MABN
    AND KB.MABS = BS.MABS
    AND BHYTCHITRA >= 0.1
    AND CHUYENKHOA = N'Nội khoa'
    AND YEAR(NGAYKHAM) = 2024
INTERSECT
SELECT BN.MABN, HOTENBN
FROM BENHNHAN BN, KHAMBENH KB, BACSI BS
WHERE BN.MABN = KB.MABN
    AND KB.MABS = BS.MABS
    AND BHYTCHITRA >= 0.1
    AND CHUYENKHOA = N'Tai mũi họng'
    AND YEAR(NGAYKHAM) = 2024;
---3.3---
SELECT T.MATHUOC, TENTHUOC
FROM THUOC T, DONTHUOC DT, CHITIETDT CT
WHERE T.MATHUOC = CT.MATHUOC
    AND CT.MADT = DT.MADT
    AND LOAITHUOC = N'Thuốc giảm đau'
    AND NGAYCAPTHUOC = '01/12/2024'
    AND TINHTRANGDT = N'Đã thanh toán'
GROUP BY T.MATHUOC, TENTHUOC
HAVING COUNT(DISTINCT DT.MADT) = 
            (SELECT COUNT(MADT)
            FROM DONTHUOC 
            WHERE NGAYCAPTHUOC = '01/12/2024'
                AND TINHTRANGDT = N'Đã thanh toán');
---3.4---
SELECT BS.MABS, HOTENBS, COUNT(MAKB) 'So luong'
FROM BACSI BS, KHAMBENH KB, BENHNHAN BN
WHERE BS.MABS = KB.MABS
    AND KB.MABN = BN.MABN
    AND SOBHYT IS NOT NULL
    AND YEAR(NGAYKHAM) = 2024
GROUP BY BS.MABS, HOTENBS
---3.5---
SELECT BN.MABN, HOTENBN
FROM BENHNHAN BN, KHAMBENH KB, DONTHUOC DT
WHERE BN.MABN = KB.MABN
    AND KB.MAKB = DT.MAKB
    AND YEAR(NGAYCAPTHUOC) = 2024
    AND TINHTRANGDT = N'Đã thanh toán'
    AND BN.MABN IN (
            SELECT TOP 1 WITH TIES MABN
            FROM KHAMBENH
            GROUP BY MABN
            ORDER BY COUNT(MAKB) DESC)
GROUP BY BN.MABN, HOTENBN
HAVING SUM(TONGTIENTT) > 250000;