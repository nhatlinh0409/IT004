CREATE DATABASE QUANLYKHAMBENH1
USE QUANLYKHAMBENH1
SET DATEFORMAT DMY
CREATE TABLE BENHNHAN (
    MaBN CHAR(5) PRIMARY KEY,
    HoTenBN NVARCHAR(50),
    NgaySinh SMALLDATETIME,
    CCCD NVARCHAR(12),
    SoBHYT NVARCHAR(15),
    BHYTChiTra FLOAT,
    DiaChi NVARCHAR(100)
);

CREATE TABLE BACSI (
    MaBS CHAR(5) PRIMARY KEY,
    HoTenBS NVARCHAR(50),
    NgayBDLV SMALLDATETIME,
    ChuyenKhoa NVARCHAR(50)
);

CREATE TABLE KHAMBENH (
    MaKB CHAR(5) PRIMARY KEY,
    MaBN CHAR(5),
    MaBS CHAR(5),
    NgayKham SMALLDATETIME,
    TrieuChung NVARCHAR(255),
    KetLuan NVARCHAR(255),
    TaiKham INT,
    FOREIGN KEY (MaBN) REFERENCES BENHNHAN(MaBN),
    FOREIGN KEY (MaBS) REFERENCES BACSI(MaBS)
);

CREATE TABLE THUOC (
    MaThuoc CHAR(5) PRIMARY KEY,
    TenThuoc NVARCHAR(50),
    LoaiThuoc NVARCHAR(50),
    DVT NVARCHAR(20),         -- đơn vị tính
    DonGia MONEY
);

CREATE TABLE DONTHUOC (
    MaDT CHAR(5) PRIMARY KEY,
    MaKB CHAR(5),
    TriGiaDT MONEY,
    BHYTChiTra FLOAT,
    NgayCapThuoc SMALLDATETIME,
    TongTienTT MONEY,
    TinhTrangDT NVARCHAR(30),
    FOREIGN KEY (MaKB) REFERENCES KHAMBENH(MaKB)
);
CREATE TABLE CHITIETDT (
    MaDT CHAR(5),
    MaThuoc CHAR(5),
    SoLuong INT,
    ThanhTien MONEY,
    PRIMARY KEY (MaDT, MaThuoc),
    FOREIGN KEY (MaDT) REFERENCES DONTHUOC(MaDT),
    FOREIGN KEY (MaThuoc) REFERENCES THUOC(MaThuoc)
);
