CREATE TRIGGER TG_CTDT
ON CHITIETDT
AFTER DELETE
AS BEGIN
    UPDATE DONTHUOC
    SET TRIGIADT = (
            SELECT SUM(THANHTIEN)
            FROM CHITIETDT
            WHERE MADT = (SELECT MADT FROM DELETED))
    WHERE MADT = (SELECT MADT FROM DELETED)
END;
