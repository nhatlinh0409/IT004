CREATE TRIGGER TG_DT
ON CHITIETDT
AFTER INSERT
AS BEGIN
    UPDATE DONTHUOC
    SET TriGiaDT = (
            SELECT SUM(ThanhTien)
            FROM CHITIETDT
            WHERE MaDT = (SELECT MaDT FROM INSERTED))
    WHERE MADT = (SELECT MaDT FROM INSERTED)
END;
