SELECT BS.MaBS, HoTenBS, BN.MaBN, HoTenBN
FROM BACSI BS, BENHNHAN BN, KHAMBENH KB
WHERE BS.MaBS = KB.MaBS 
    AND BN.MaBN = KB.MaBN
    AND ChuyenKhoa = N'Tai mũi họng'
    AND YEAR(NgayKham) = 2024;
---3.2---
SELECT BN.MaBN, HoTenBN
FROM BENHNHAN BN, KHAMBENH KB
WHERE BN.MaBN = KB.MaBN
    AND YEAR(NgayKham) = 2024
EXCEPT
SELECT BN.MaBN, HoTenBN
FROM BENHNHAN BN, KHAMBENH KB, DONTHUOC DT, CHITIETDT CT
WHERE BN.MaBN = KB.MaBN
    AND KB.MaKB = DT.MaKB
    AND DT.MaDT = CT.MaDT
    AND TinhTrangDT = N'Đã thanh toán'
    AND TongTienTT >= 100000;
---3.3---
SELECT DT.MaDT, MaKB
FROM DONTHUOC DT, CHITIETDT CT, THUOC T
WHERE DT.MaDT = CT.MaDT
    AND CT.MaThuoc = T.MaThuoc
    AND YEAR(NgayCapThuoc) = 2024
    AND TinhTrangDT = N'Đã thanh toán'
    AND LoaiThuoc = N'Thuốc dị ứng'
GROUP BY DT.MaDT, MaKB, DT.MaDT
HAVING COUNT(DISTINCT T.MaThuoc) = 
                (SELECT COUNT(MaThuoc)
                FROM THUOC
                WHERE LoaiThuoc = N'Thuốc dị ứng');
---3.4---
SELECT BN.MaBN, HoTenBN, COUNT(DT.MADT) 'So luong'
FROM BENHNHAN BN, KHAMBENH KB, DONTHUOC DT
WHERE BN.MaBN = KB.MaBN
    AND KB.MaKB = DT.MaKB
    AND YEAR(NgayCapThuoc) = 2024
    AND TinhTrangDT = N'Đã thanh toán'
    AND SoBHYT IS NULL
GROUP BY BN.MaBN, HoTenBN;
---3.5---
SELECT BN.MaBN, HoTenBN
FROM BENHNHAN BN, DONTHUOC DT, KHAMBENH KB
WHERE BN.MaBN = KB.MaBN
    AND DT.MaKB = KB.MaKB
    AND YEAR(NgayCapThuoc) = 2024
    AND BN.MaBN IN (
            SELECT TOP 1 WITH TIES MaBN
            FROM KHAMBENH
            GROUP BY MaBN
            ORDER BY COUNT(MAKB))
GROUP BY BN.MaBN, HoTenBN
HAVING SUM(TongTienTT) < 100000;



