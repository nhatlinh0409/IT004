CREATE DATABASE QLCTPT
USE QLCTPT
SET DATEFORMAT DMY
CREATE TABLE PHONGTRO (
	MAPT CHAR(5) PRIMARY KEY,
	TENPT NVARCHAR(50),
	DIENTICH FLOAT,
	GIAPT MONEY,
	TINHTRANGPT NVARCHAR(20)
)
CREATE TABLE CUDAN (
	MACD CHAR(5) PRIMARY KEY,
	HOTEN NVARCHAR(50),
	CCCD NVARCHAR(12),
	DIACHI NVARCHAR(100),
	SODT VARCHAR(15),
	NGAYTHUE SMALLDATETIME,
	TRANGTHAICD NVARCHAR(15)
)
CREATE TABLE HOPDONG (
	MAHD CHAR(5) PRIMARY KEY,
	MACD CHAR(5) FOREIGN KEY REFERENCES CUDAN(MACD),
	MAPT CHAR(5) FOREIGN KEY REFERENCES PHONGTRO(MAPT),
	NGAYKY SMALLDATETIME,
	NGAYHETHAN SMALLDATETIME,
	TRANGTHAIHD NVARCHAR(20)
)
CREATE TABLE DICHVU (
	MADV CHAR(5) PRIMARY KEY,
	TENDV NVARCHAR(50),
	DONGIA MONEY
)
CREATE TABLE PHIEUTINHTIEN (
	MAPTT CHAR(5) PRIMARY KEY,
	MAHD CHAR(5) FOREIGN KEY REFERENCES HOPDONG(MAHD),
	SOTIENDICHVU MONEY,
	SOTIENTHUEPT MONEY,
	TONGTIENTT MONEY,
	NGAYTINHTIEN SMALLDATETIME,
	TINHTRANGTT NVARCHAR(20),
	PHUONGTHUCTT NVARCHAR(20)
)
CREATE TABLE CHITIETTTDV (
	MAPTT CHAR(5) FOREIGN KEY REFERENCES PHIEUTINHTIEN(MAPTT),
	MADV CHAR(5) FOREIGN KEY REFERENCES DICHVU(MADV),
	CHISODV FLOAT,
	THANHTIEN MONEY,
	PRIMARY KEY (MAPTT, MADV)
)
---2.1---
ALTER TABLE PHONGTRO
ADD CONSTRAINT CK_PT
CHECK (GIAPT BETWEEN 500000 AND 20000000);
---2.2---
ALTER TABLE CUDAN
ADD CONSTRAINT CK_CD
CHECK (TRANGTHAICD IN (N'Đang ở', N'Đã rời đi'));
---2.3---
GO
CREATE TRIGGER TG_CT
ON CHITIETTTDV
AFTER UPDATE 
AS BEGIN
	UPDATE CHITIETTTDV
	SET THANHTIEN = CHISODV*(
		SELECT DONGIA
		FROM DICHVU
		WHERE MADV = CHITIETTTDV.MADV)
	WHERE MADV IN (SELECT MADV FROM INSERTED)
		AND MADV IN (SELECT MADV FROM DELETED)
END;

---3.1---
SELECT CD.MACD, HOTEN, PT.MAPT, TENPT
FROM CUDAN CD, PHONGTRO PT, HOPDONG HD
WHERE CD.MACD = HD.MACD
	AND PT.MAPT = HD.MAPT
	AND TRANGTHAIHD = N'Đã hết hạn'
	AND YEAR(NGAYHETHAN) = 2024;
---3.2---
SELECT HD.MAHD, MAPT
FROM HOPDONG HD, PHIEUTINHTIEN PTT
WHERE HD.MAHD = PTT.MAHD
	AND TINHTRANGTT = N'Đã thanh toán'
	AND YEAR(NGAYTINHTIEN) = 2024
EXCEPT
SELECT HD.MAHD, MAPT
FROM HOPDONG HD, PHIEUTINHTIEN PTT, CHITIETTTDV CT
WHERE HD.MAHD = PTT.MAHD
	AND PTT.MAPTT = CT.MAPTT
	AND CHISODV >= 5;
---3.3---
SELECT DV.MADV, TENDV
FROM DICHVU DV, CHITIETTTDV CT, PHIEUTINHTIEN PTT
WHERE DV.MADV = CT.MADV
	AND CT.MAPTT = PTT.MAPTT
	AND DONGIA > 10000
	AND NGAYTINHTIEN = '15/12/2024'
GROUP BY DV.MADV, TENDV
HAVING COUNT(DISTINCT PTT.MAPTT) =
		(SELECT COUNT(MAPTT)
		FROM PHIEUTINHTIEN
		WHERE NGAYTINHTIEN = '15/12/2024');
---3.4---
SELECT HD.MAHD, MACD, COUNT(MAPTT)
FROM HOPDONG HD, PHIEUTINHTIEN PTT
WHERE HD.MAHD = PTT.MAHD
	AND YEAR(NGAYTINHTIEN) = 2024
	AND TINHTRANGTT = N'Đã thanh toán'
	AND TRANGTHAIHD = N'Đã hết hạn'
GROUP BY HD.MAHD, MACD;
---3.5---
 SELECT CD.MACD, HOTEN
 FROM CUDAN CD, HOPDONG HD, PHIEUTINHTIEN PTT
 WHERE CD.MACD = HD.MACD
	AND HD.MAHD = PTT.MAHD
	AND TINHTRANGTT = N'Đã thanh toán'
	AND YEAR(NGAYTINHTIEN) = 2024
	AND CD.MACD IN (
			SELECT TOP 1 WITH TIES MACD
			FROM HOPDONG
			GROUP BY MACD
			ORDER BY COUNT(MAHD) ASC)
GROUP BY CD.MACD, HOTEN
HAVING SUM(TONGTIENTT) > 5000000;