CREATE DATABASE QUANLYCHOTHUEPHONGTRO2
USE QUANLYCHOTHUEPHONGTRO2
SET DATEFORMAT DMY
CREATE TABLE PHONGTRO (
	MAPT CHAR(5) PRIMARY KEY,
	TENPT NVARCHAR(50),
	DIENTICH FLOAT,
	LOAIPT NVARCHAR(15),
	GIAPT MONEY,
	TINHTRANGPT NVARCHAR(20)
)
CREATE TABLE CUDAN (
	MACD CHAR(5) PRIMARY KEY,
	HOTEN NVARCHAR(50),
	CCCD NVARCHAR(12),
	DIACHI NVARCHAR(100),
	SODT VARCHAR(15),
	TRANGTHAICD NVARCHAR(15)
)
CREATE TABLE HOPDONG (
	MAHD CHAR(5) PRIMARY KEY,
	MACD CHAR(5) FOREIGN KEY REFERENCES CUDAN(MACD),
	MAPT CHAR(5) FOREIGN KEY REFERENCES PHONGTRO(MAPT),
	NGAYKY SMALLDATETIME,
	NGAYHETHAN SMALLDATETIME,
	TRANGTHAIHD NVARCHAR(20)
)
CREATE TABLE DICHVU (
	MADV CHAR(5) PRIMARY KEY,
	TENDV NVARCHAR(50),
	DONGIA MONEY
)
CREATE TABLE PHIEUTINHTIEN (
	MAPTT CHAR(5) PRIMARY KEY,
	MAHD CHAR(5) FOREIGN KEY REFERENCES HOPDONG(MAHD),
	SOTIENDICHVU MONEY,
	SOTIENTHUEPT MONEY,
	TONGTIENTT MONEY,
	NGAYTINHTIEN SMALLDATETIME,
	TINHTRANGTT NVARCHAR(20),
	PHUONGTHUCTT NVARCHAR(20)
)
CREATE TABLE CHITIETTTDV (
	MAPTT CHAR(5) FOREIGN KEY REFERENCES PHIEUTINHTIEN(MAPTT),
	MADV CHAR(5) FOREIGN KEY REFERENCES DICHVU(MADV),
	CHISODV FLOAT,
	THANHTIEN MONEY,
	CONSTRAINT PK_CT PRIMARY KEY (MAPTT, MADV)
)
---2.1---
ALTER TABLE HOPDONG
ADD CONSTRAINT CK_HD
CHECK (NGAYKY <= NGAYHETHAN);
---2.2---
ALTER TABLE PHONGTRO
ADD CONSTRAINT CK_PT
CHECK (TINHTRANGPT IN (N'Trống', N'Đã cho thuê'));
---2.3---
GO
CREATE TRIGGER TG_CTDV
ON CHITIETTTDV
AFTER DELETE
AS BEGIN
	UPDATE PHIEUTINHTIEN
	SET SOTIENDICHVU = (
		SELECT SUM(THANHTIEN)
		FROM CHITIETTTDV
		WHERE MAPTT = (SELECT MAPTT FROM DELETED))
	WHERE MAPTT = (SELECT MAPTT FROM DELETED)
END;
---3.1---
SELECT PT.MAPT, TENPT, MAPTT, TONGTIENTT
FROM PHONGTRO PT, HOPDONG HD, PHIEUTINHTIEN PTT
WHERE PT.MAPT = HD.MAPT
	AND HD.MAHD = PTT.MAHD
	AND TINHTRANGPT = N'Đã cho thuê'
	AND YEAR(NGAYTINHTIEN) = 2024;
---3.2---
SELECT CD.MACD, HOTEN
FROM CUDAN CD, HOPDONG HD, PHONGTRO PT
WHERE CD.MACD = HD.MACD
	AND HD.MAPT = PT.MAPT
	AND DIENTICH > 20
	AND YEAR(NGAYKY) = 2024
	AND LOAIPT = N'Kiot'
INTERSECT
SELECT CD.MACD, HOTEN
FROM CUDAN CD, HOPDONG HD, PHONGTRO PT
WHERE CD.MACD = HD.MACD
	AND HD.MAPT = PT.MAPT
	AND DIENTICH > 20
	AND YEAR(NGAYKY) = 2024
	AND LOAIPT = N'Có gác xép';
---3.3---
SELECT PTT.MAPTT, MAHD
FROM PHIEUTINHTIEN PTT, CHITIETTTDV CT, DICHVU DV
WHERE PTT.MAPTT = CT.MAPTT
	AND CT.MADV = DV.MADV
	AND TONGTIENTT > 2000000
	AND PHUONGTHUCTT = N'Tiền mặt'
	AND DONGIA <= 50000
GROUP BY PTT.MAPTT, MAHD
HAVING COUNT(DISTINCT DV.MADV) = 
			(SELECT COUNT(MADV)
			FROM DICHVU
			WHERE DONGIA <= 50000);
---3.4---
SELECT CD.MACD, HOTEN, COUNT(MAHD) 'Số lượng'
FROM CUDAN CD, HOPDONG HD
WHERE CD.MACD = HD.MACD
	AND TRANGTHAIHD = N'Đã hết hạn'
	AND TRANGTHAICD = N'Đang ở'
	AND YEAR(NGAYHETHAN) = 2024
GROUP BY CD.MACD, HOTEN;
---3.5---
SELECT HD.MAHD
FROM HOPDONG HD, PHIEUTINHTIEN PTT
WHERE HD.MAHD = PTT.MAHD
	AND TINHTRANGTT = N'Đã thanh toán'
	AND HD.MAHD IN (
		SELECT TOP 1 WITH TIES MAHD
		FROM PHIEUTINHTIEN PTT, CHITIETTTDV CT, DICHVU DV
		WHERE PTT.MAPTT = CT.MAPTT
			AND CT.MADV = DV.MADV
			AND TENDV = N'Điện'
		GROUP BY MAHD
		ORDER BY SUM(CHISODV) ASC)
GROUP BY HD.MAHD
HAVING COUNT(DISTINCT MAPTT) >= 2;