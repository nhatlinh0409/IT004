CREATE DATABASE QUANLYCHOTHUEPHONGTRO1
USE QUANLYCHOTHUEPHONGTRO1
SET DATEFORMAT DMY
CREATE TABLE PHONGTRO (
	MAPT CHAR(5) PRIMARY KEY,
	TENPT NVARCHAR(50),
	DIENTICH FLOAT,
	LOAIPT NVARCHAR(15),
	GIAPT MONEY,
	TINHTRANGPT NVARCHAR(20)
)
CREATE TABLE CUDAN (
	MACD CHAR(5) PRIMARY KEY,
	HOTEN NVARCHAR(50),
	CCCD NVARCHAR(12),
	DIACHI NVARCHAR(100),
	SODT VARCHAR(15),
	NGAYTHUE SMALLDATETIME,
	TRANGTHAICD NVARCHAR(15)
)
CREATE TABLE HOPDONG (
	MAHD CHAR(5) PRIMARY KEY,
	MACD CHAR(5) FOREIGN KEY REFERENCES CUDAN(MACD),
	MAPT CHAR(5) FOREIGN KEY REFERENCES PHONGTRO(MAPT),
	NGAYKY SMALLDATETIME,
	NGAYHETHAN SMALLDATETIME,
	TRANGTHAIHD NVARCHAR(20)
)
CREATE TABLE DICHVU (
	MADV CHAR(5) PRIMARY KEY,
	TENDV NVARCHAR(50),
	DONGIA MONEY
)
CREATE TABLE PHIEUTINHTIEN (
	MAPTT CHAR(5) PRIMARY KEY,
	MAHD CHAR(5) FOREIGN KEY REFERENCES HOPDONG(MAHD),
	SOTIENDICHVU MONEY,
	SOTIENTHUEPT MONEY,
	TONGTIENTT MONEY,
	NGAYTINHTIEN SMALLDATETIME,
	TINHTRANGTT NVARCHAR(20),
	PHUONGTHUCTT NVARCHAR(20)
)
CREATE TABLE CHITIETTTDV (
	MAPTT CHAR(5) FOREIGN KEY REFERENCES PHIEUTINHTIEN(MAPTT),
	MADV CHAR(5) FOREIGN KEY REFERENCES DICHVU(MADV),
	CHISODV FLOAT,
	THANHTIEN MONEY,
	CONSTRAINT PK_CT PRIMARY KEY (MAPTT, MADV)
)
---2.1---
ALTER TABLE DICHVU
ADD CONSTRAINT CK_DV
CHECK (DONGIA BETWEEN 2000 AND 500000);
---2.2---
ALTER TABLE PHONGTRO
ADD CONSTRAINT CK_PT
CHECK (LOAIPT IN (N'Kiot', N'Có gác xép', N'Không gác xép'));
---2.3---
GO
CREATE TRIGGER TG_CTDV
ON PHIEUTINHTIEN
AFTER INSERT
AS BEGIN
	UPDATE PHIEUTINHTIEN
	SET SOTIENDICHVU = (
				SELECT SUM(THANHTIEN)
				FROM CHITIETTTDV CT
				WHERE MAPTT = (SELECT MAPTT FROM INSERTED))
	WHERE MAPTT IN (SELECT MAPTT FROM INSERTED)
END;
---3.1---
SELECT PTT.MAPTT, MAHD, CHISODV, THANHTIEN
FROM PHIEUTINHTIEN PTT, CHITIETTTDV CT, DICHVU DV
WHERE PTT.MAPTT = CT.MAPTT
	AND DV.MADV = CT.MADV
	AND YEAR(NGAYTINHTIEN) = 2024
	AND TENDV = N'Điện';
---3.2---
SELECT PT.MAPT, TENPT
FROM PHONGTRO PT, HOPDONG HD
WHERE PT.MAPT = HD.MAPT
	AND LOAIPT = N'Không gác xép'
	AND YEAR(NGAYKY) = 2024
EXCEPT
SELECT PT.MAPT, TENPT
FROM PHONGTRO PT, HOPDONG HD, PHIEUTINHTIEN PTT
WHERE PT.MAPT = HD.MAPT
	AND HD.MAHD = PTT.MAHD
	AND PHUONGTHUCTT = N'Chuyển khoản'
	AND TONGTIENTT > 4000000
---3.3---
SELECT CD.MACD, HOTEN 
FROM CUDAN CD, HOPDONG HD, PHONGTRO PT
WHERE CD.MACD = HD.MACD
	AND HD.MAPT = PT.MAPT
	AND TRANGTHAICD = N'Đang ở'
	AND LOAIPT = N'Kiot'
	AND DIENTICH = 40
GROUP BY CD.MACD, HOTEN
HAVING COUNT(DISTINCT PT.MAPT) = 
			(SELECT COUNT(MAPT)
			FROM PHONGTRO
			WHERE LOAIPT = N'Kiot'
				AND DIENTICH = 40);
---3.4---
SELECT CD.MACD, HOTEN, COUNT(MAHD) 'So luong'
FROM CUDAN CD, HOPDONG HD
WHERE CD.MACD = HD.MACD
	AND TRANGTHAICD = N'Đã rời đi'
	AND YEAR(NGAYKY) BETWEEN 2022 AND 2024
GROUP BY CD.MACD, HOTEN;
---3.5---
SELECT TOP 1 WITH TIES HD.MAHD
FROM HOPDONG HD, PHIEUTINHTIEN PTT, CHITIETTTDV CT, DICHVU DV
WHERE HD.MAHD = PTT.MAHD
	AND PTT.MAPTT = CT.MAPTT
	AND CT.MADV = DV.MADV
	AND TENDV = N'Điện'
	AND HD.MAHD IN (
			SELECT MAHD
			FROM PHIEUTINHTIEN
			WHERE TINHTRANGTT = N'Đã thanh toán'
			GROUP BY MAHD
			HAVING COUNT(MAPTT) >= 2)
GROUP BY HD.MAHD
ORDER BY SUM(CHISODV) ASC;
